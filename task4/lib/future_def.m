function F = future_def(level)
% FUTURE_DEF  미래(2035~2040년 가정) 계통 시나리오 정의
%   level = 'peak'  : 여름 최대부하 (기존 부하 ×1.15) + AI 부하
%   level = 'light' : 봄철 낮 경부하 (기존 부하 ×0.60) + AI 부하(24시간 일정) + 재생E 최대출력
%
%   ※ 수치는 제11차 전력수급기본계획 방향(재생E 확대, 석탄 축소, 원전 추가,
%     용인 반도체 클러스터·수도권 데이터센터 수요 증가)을 참고한 '가정값'임
    switch level
        case 'peak',  F.load_scale = 1.15;
        case 'light', F.load_scale = 0.60;
    end
    % (1) AI·반도체 신규 부하 10 GW
    F.ai = [21 3000;   % 동용인 - 용인 반도체 클러스터
            23 3000;   % 서용인 - 용인 반도체 클러스터
            161 1000;  % 김포   - 데이터센터
            166 1000;  % 시흥   - 데이터센터
            104 500;   % 구로금천 - 데이터센터
            28 500;    % 안양   - 데이터센터
            37 500;    % 고양   - 데이터센터
            33 500];   % 하남   - 데이터센터
    % (2) 재생E 23 GW 추가 (서남해안 해상풍력·태양광 집중)
    F.re = [89 5000;   % 신안 해상풍력
            98 3000;   % 해남 태양광
            92 3000;   % 영암 태양광
            91 2000;   % 영광 풍력·태양광
            171 3000;  % 군산 새만금
            176 2000;  % 부안 해상풍력
            117 2000;  % 영덕 풍력
            74 1000;   % 청송 풍력
            49 2000];  % 남해 해상풍력
    if strcmp(level, 'peak')   % 여름 저녁 피크: 태양광 출력 감소 → 재생E 40 % 출력 가정
        F.re(:,2) = F.re(:,2) * 0.4;
    end
    % (3) 충남 석탄 폐지 (보령, 태안 11 GW) → 태안 LNG 전환 2 GW
    F.retire = {[128 138], 'Coal'};
    % (4) 신규 발전 : 울진 신한울 3·4호기 2.8 GW, 태안 LNG 2 GW, 용인 클러스터 LNG 3 GW
    F.newgen = [72 1400 1400 1;
                72 1400 1400 1;
                138 1000 400 3;
                138 1000 400 3;
                21 1500 600 3;
                21 1500 600 3];
end
