function S = scen2032()
% SCEN2032  2032년 계통 시나리오 정의 (공식 자료 기반)
%   각 항목의 src 에 출처를, 공식 수치가 없어 정한 값은 '[추정]'으로 표시
%
%   기준 시점 : 2032년 (KPG193 = 현재 계통으로 보고 약 8년 뒤)
%   - 송전망 사업 중 준공 시기가 공식 발표된 것만 반영
%   - 2033년 이후 준공 예정 설비(신한울 3·4호기, 서해안 HVDC 2~4단계 등)는 제외

%% 1. 수요
S.growth_rate = 0.018;    % 연평균 최대수요 증가율
S.growth_src  = '제11차 전력수급기본계획 (2025.2 확정): 목표수요 연평균 1.8 % 증가';
S.years       = 8;        % 2024 → 2032
S.peak_scale  = (1 + S.growth_rate) ^ S.years;   % = 1.153

S.light_ratio = 0.40;     % 봄철 낮 최저수요 / 최대수요
S.light_src   = '산업부 봄철 전력수급 대책 (2024): 최저수요 37.3 GW ≈ 최대수요의 약 40 %';

% 용인 반도체 산단 1단계 (2032년까지): 산단 내 1 GW LNG 3기로 초기 수요 대응
% → 2032년 수요는 공식 수치가 없어 1단계 공급설비 용량(3 GW)과 같다고 [추정]
S.yongin_load = [21 1500; 23 1500];              % [모선 MW] 동용인, 서용인
S.yongin_src  = '기후에너지환경부 (2026.8): 용인 산단 2041년까지 14 GW 이상, 1단계(~2032) LNG 1 GW×3기 [2032 수요 = 3 GW 추정]';

% 데이터센터: 2038년 4.4 GW (11차 전기본) → 2024~2038 선형 보간하면 2032년 약 2.5 GW
S.dc_total = 4400 * 8/14;                        % 2514 MW
S.dc_metro_share = 0.68;                         % 계획 중 신규 데이터센터의 수도권 비중
S.dc_src  = '11차 전기본: 2038 데이터센터 4.4 GW / 신규 계획 데이터센터 68 % 수도권 (한전·업계 자료) [선형 보간]';
S.dc_metro_bus = [161 166 104 28 37 33 164];     % 김포 시흥 구로금천 안양 고양 하남 부천 [균등 배분 추정]
S.dc_other_bus = [145 2 98 112];                 % 부산 강원 해남 대구 [균등 배분 추정]

%% 2. 재생에너지 (설비 증가분만 추가, 기존 설비는 KPG193 부하에 이미 반영된 것으로 봄)
S.solar_now = 30.8;   S.wind_now = 2.3;          % GW, 2024
S.solar_2030 = 55.7;  S.wind_2030 = 18.3;        % GW, 11차 전기본
S.solar_2038 = 77.2;  S.wind_2038 = 40.7;
S.re_src = '11차 전기본: 2030 태양광 55.7·풍력 18.3 GW, 2038 태양광 77.2·풍력 40.7 GW / 2024 태양광 30.8 GW';
S.solar_2032 = S.solar_2030 + (S.solar_2038 - S.solar_2030) * 2/8;   % 61.1 GW
S.wind_2032  = S.wind_2030  + (S.wind_2038  - S.wind_2030)  * 2/8;   % 23.9 GW
S.solar_add = (S.solar_2032 - S.solar_now) * 1000;                  % MW
S.wind_add  = (S.wind_2032  - S.wind_now)  * 1000;

% 태양광 지역 배분: 2023 보급통계 전남 5,898 MW·전북 4,461 MW / 전국 22,846 MW
S.solar_share = struct('jeonnam', 5898/22846, 'jeonbuk', 4461/22846);
S.solar_share_src = '한국에너지공단 2023 신재생에너지 보급통계 (전남 25.8 %, 전북 19.5 %)';
S.solar_jn_bus = [89 98 92 91 85 76];            % 신안 해남 영암 영광 무안 고흥
S.solar_jb_bus = [170 172 176 171 182];          % 고창 김제 부안 군산 정읍
S.solar_rest_bus = [5 6 13 16 35 51 53 62 71 74];% KPG193 기존 재생E 모선 (기존 출력 비례 배분)

% 풍력 지역 배분 [추정]: 해상풍력 추진 지역 기준
S.wind_alloc = [89 0.30; 91 0.15; 98 0.10;       % 전남 서남해 55 %
                176 0.05; 170 0.05;              % 전북 서남해 10 %
                144 0.15;                        % 울산 부유식 15 %
                167 0.10;                        % 인천 해상 10 %
                117 0.03; 74 0.03; 13 0.02; 4 0.02];  % 경북·강원 육상 10 %
S.wind_src = '[추정] 서남해·울산 부유식·인천 해상풍력 추진 지역 비중';

% 시간대별 출력 비율 [추정]: 감도분석으로 확인
S.cf.peak  = struct('solar', 0.15, 'wind', 0.15);   % 여름 17~18시
S.cf.light = struct('solar', 0.70, 'wind', 0.25);   % 봄 12~13시
S.cf_src = '[추정] 여름 최대부하 시각(17~18시) 태양광 15 %, 봄 정오 70 % → 감도분석 수행';

%% 3. 발전설비
% 석탄 → LNG 전환 (2023~2030, 18기 9.1 GW): 삼천포3~6, 태안1~4, 하동1~4, 당진1~4, 보령5·6
S.coal_conv = [52  2240;    % 사천(삼천포 3~6) [MW]
               138 2000;    % 태안 1~4
               49  2000;    % 남해(하동 1~4)
               125 2000;    % 당진 1~4 → 용인 반도체 클러스터 LNG로 이전
               128 1000];   % 보령 5·6
S.coal_relocate = [125 0];  % 당진 물량은 같은 자리에 LNG 를 짓지 않음 (용인 LNG 로 대체)
S.coal_src = '11차 전기본: 2023~2030 석탄 18기(9.1 GW) LNG 전환, 당진 4기는 반도체 클러스터 이전 / [나머지는 같은 부지 LNG 전환 추정]';
S.yongin_lng = [21 1000; 21 1000; 23 1000];      % 용인 산단 LNG 1 GW × 3기

% 신한울 3호기 2032.10 준공 → 2032년 여름·봄 시점에는 미반영
S.nuke_src = '한수원: 신한울 3호기 2032.10, 4호기 2033 준공 예정 → 미반영';

%% 4. 송전망 (2032년까지 준공 예정인 HVDC)
%        송전  수전  P_MW  손실
%   변환소는 실제처럼 345/765 kV 변전소에 연결 : 모델에서 가장 가까운 345 kV 이상 모선 사용
S.hvdc = [72   41   4000  0.03;     % 동해안(울진 765) → 신가평 4 GW, 2027.6 준공 예정 [모델: 양평 765 kV, 38 km]
          72   39   4000  0.03;     % 동해안(울진 765) → 동서울 4 GW, 2027.6 준공 예정 [모델: 남양주 345 kV, 7 km]
          132  26   2000  0.03];    % 새만금 → 서화성 2 GW, 2031 준공 예정 [모델: 서천 345 kV → 안산 345 kV]
S.hvdc_name = {'동해안→신가평', '동해안→동서울', '새만금→서화성'};
S.hvdc_src = '산업부 전원개발 실시계획 변경(2027.6 준공) / 11차 장기 송변전설비계획 서해안 HVDC 1단계(2031)';
end
